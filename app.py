def is_postgres() -> bool:
    return bool(current_app.config["DATABASE_URL"])


def get_connection():
    database_url = current_app.config["DATABASE_URL"]
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(database_url, row_factory=dict_row)

    connection = sqlite3.connect(current_app.config["DATABASE"])
    connection.row_factory = sqlite3.Row
    return connection


def execute_query(connection, query: str, parameters: tuple = ()):
    if is_postgres():
        query = query.replace("?", "%s")
    return connection.execute(query, parameters)


def initialize_database() -> None:
    if not is_postgres():
        database_path = current_app.config["DATABASE"]
        Path(database_path).parent.mkdir(parents=True, exist_ok=True)

    with closing(get_connection()) as connection:
        if is_postgres():
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS beers (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL UNIQUE,
                    abv_style TEXT NOT NULL,
                    description TEXT NOT NULL,
                    tags TEXT NOT NULL,
                    sort_order INTEGER NOT NULL UNIQUE
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS contact_messages (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    contact TEXT NOT NULL,
                    message TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
        else:
            connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS beers (
                    id INTEGER PRIMARY KEY,
                    name TEXT NOT NULL UNIQUE,
                    abv_style TEXT NOT NULL,
                    description TEXT NOT NULL,
                    tags TEXT NOT NULL,
                    sort_order INTEGER NOT NULL UNIQUE
                );

                CREATE TABLE IF NOT EXISTS contact_messages (
                    id INTEGER PRIMARY KEY,
                    name TEXT NOT NULL,
                    contact TEXT NOT NULL,
                    message TEXT NOT NULL,
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                );
                """
            )

        beer_count = execute_query(
            connection, "SELECT COUNT(*) AS count FROM beers"
        ).fetchone()["count"]
        if beer_count == 0:
            connection.executemany(
                """
                INSERT INTO beers (name, abv_style, description, tags, sort_order)
                VALUES (?, ?, ?, ?, ?)
                ON CONFLICT DO NOTHING
                """,
                (
                    (name, abv_style, description, json.dumps(tags), order)
                    for order, (name, abv_style, description, tags) in enumerate(BEERS)
                ),
            )
        connection.commit()


def get_beers() -> list[dict[str, object]]:
    with closing(get_connection()) as connection:
        rows = execute_query(
            connection,
            """
            SELECT name, abv_style, description, tags
            FROM beers
            ORDER BY sort_order
            """,
        ).fetchall()

    return [
        {
            "name": row["name"],
            "abv_style": row["abv_style"],
            "description": row["description"],
            "tags": json.loads(row["tags"]),
        }
        for row in rows
    ]


def render_home(
    *,
    status: str | None = None,
    error: str | None = None,
    form_data: dict[str, str] | None = None,
    status_code: int = 200,
):
    return (
        render_template(
            "index.html",
            beers=get_beers(),
            status=status,
            error=error,
            form_data=form_data or {},
        ),
        status_code,
    )


def create_app(test_config: dict[str, object] | None = None) -> Flask:
    app = Flask(__name__, instance_relative_config=True, static_folder=None)
    app.config.from_mapping(
        DATABASE_URL=os.environ.get("DATABASE_URL"),
        DATABASE=os.environ.get(
            "DATABASE_PATH", str(Path(app.instance_path) / "site.db")
        ),
    )
    if test_config:
        app.config.update(test_config)

    if os.environ.get("VERCEL") and not app.config["DATABASE_URL"]:
        raise RuntimeError(
            "Set DATABASE_URL to a persistent PostgreSQL database before deploying to Vercel."
        )

    with app.app_context():
        initialize_database()

    @app.get("/")
    def index():
        return render_home()

    @app.get("/beer-label.webp")
    def beer_label():
        return send_from_directory(Path(app.root_path) / "public", "beer-label.webp")

    @app.post("/contact")
    def contact():
        name = request.form.get("name", "").strip()
        contact_details = request.form.get("contact", "").strip()
        message = request.form.get("message", "").strip()
        form_data = {
            "name": name,
            "contact": contact_details,
            "message": message,
        }

        if not name or len(name) > 100:
            return render_home(
                error="Вкажіть ім’я (не більше 100 символів).",
                form_data=form_data,
                status_code=400,
            )
        if not contact_details or len(contact_details) > 200:
            return render_home(
                error="Вкажіть телефон або email (не більше 200 символів).",
                form_data=form_data,
                status_code=400,
            )
        if not message or len(message) > 2000:
            return render_home(
                error="Вкажіть повідомлення (до 2000 символів).",
                form_data=form_data,
                status_code=400,
            )

        with closing(get_connection()) as connection:
            execute_query(
                connection,
                """
                INSERT INTO contact_messages (name, contact, message)
                VALUES (?, ?, ?)
                """,
                (name, contact_details, message),
            )
            connection.commit()

        return render_home(status="Дякуємо! Ваше повідомлення збережено.")

    @app.get("/health")
    def health():
        with closing(get_connection()) as connection:
            execute_query(connection, "SELECT 1").fetchone()
        return {"status": "ok"}

    return app


app = create_app()


if __name__ == "__main__":
    print("Сайт доступний за адресою: http://127.0.0.1:5000")
    app.run(host="127.0.0.1", port=5000)
